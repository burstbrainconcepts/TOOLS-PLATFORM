"""Turns captured human motion into a clip our characters can play.
Input: skeleton_motion.npz written by VideoIntoBlenderModel (v2bm): 24 SMPL-style joints per frame, pelvis-centred, y up, forward = -z.
Steps: remove the body's heading (so the clip always faces forward), convert to our rig frame (forward +z, character's left = +x),
cut a time range, optionally find the best seamless loop, estimate the floor speed that keeps planted feet still, and write src/mocap/<name>.json
plus the registry src/mocap/index.ts (so the renderer can import it).
Usage: python build-clip.py <skeleton_motion.npz> <name> [--start S --end E] [--loop]   (times in seconds)"""
import numpy as np, json, sys, os, glob
args = sys.argv[1:]
npz, name = args[0], args[1]
opt = lambda k, d=None: float(args[args.index(k) + 1]) if k in args else d
d = np.load(npz); J = d['joints_3d'].astype(np.float64); names = [str(n) for n in d['joint_names']]; ix = {n: i for i, n in enumerate(names)}
fps = float(d['fps']); n = len(J)
s0 = int(round((opt('--start', 0.0)) * fps)); s1 = int(round((opt('--end', n / fps)) * fps)); s1 = min(s1, n)
J = J[s0:s1]
# 1. heading per frame from the hips (and shoulders): forward (-z in the source frame) is perpendicular to the right-hip -> left-hip line
def heading(Jf):
    r = (Jf[:, ix['right_hip']] - Jf[:, ix['left_hip']]) + (Jf[:, ix['right_shoulder']] - Jf[:, ix['left_shoulder']])
    f = np.stack([r[:, 2], -r[:, 0]], 1)                       # forward in (x, z): r = (1,0) -> (0,-1)
    return np.unwrap(np.arctan2(f[:, 0], -f[:, 1]))             # angle from the straight-ahead direction (0, -1)
yaw = heading(J); k = np.ones(5) / 5; yaw = np.convolve(np.pad(yaw, 2, mode='edge'), k, 'valid')
c, s = np.cos(-yaw), np.sin(-yaw)
R = J.copy(); R[:, :, 0] = J[:, :, 0] * c[:, None] - J[:, :, 2] * s[:, None]; R[:, :, 2] = J[:, :, 0] * s[:, None] + J[:, :, 2] * c[:, None]
# 2. into our frame: (x, y, z) -> (-x, y, -z)  (our forward is +z, the character's left is +x)
P = R.copy(); P[:, :, 0] *= -1; P[:, :, 2] *= -1
# 3. ground and standing hip height
feet = P[:, [ix['left_foot'], ix['right_foot'], ix['left_ankle'], ix['right_ankle']], 1]
ground = float(np.percentile(feet.min(1), 2)); hip = P[:, ix['pelvis'], 1] - ground
hipRef = float(np.percentile(hip, 75))
# 4. optional seamless loop: the pair of frames (a, b), 0.6 s or longer, whose poses (and velocities) are closest
loop = '--loop' in args
if loop:
    X = (P - P[:, [ix['pelvis']]]).reshape(len(P), -1); best = (1e9, 0, len(P) - 1); mn = int(0.6 * fps)
    for a in range(0, len(P) - mn):
        for b in range(a + mn, len(P)):
            dist = np.linalg.norm(X[a] - X[b]) + 0.5 * np.linalg.norm((X[min(a + 1, len(P) - 1)] - X[a]) - (X[min(b + 1, len(P) - 1)] - X[b]))
            if dist < best[0]: best = (dist, a, b)
    _, a, b = best; P = P[a:b]; hip = hip[a:b]; yaw = yaw[a:b]; print(f'loop frames {a}..{b} ({(b - a) / fps:.2f} s), closure distance {best[0]:.3f}')
# 5. floor speed: backward speed of a planted foot relative to the pelvis (mocap metres/s); planted = foot close to the lowest foot height
speeds = []
for side in ('left', 'right'):
    fz = P[:, ix[f'{side}_ankle'], 2] - P[:, ix['pelvis'], 2]; fy = P[:, ix[f'{side}_ankle'], 1]
    low = fy < np.percentile(fy, 25) + 0.02
    v = np.gradient(fz) * fps
    speeds += [-v[i] for i in range(1, len(v) - 1) if low[i] and low[i - 1] and low[i + 1] and v[i] < 0]
floorSpeed = float(np.median(speeds)) if len(speeds) > 8 else 0.0
clip = {'name': name, 'fps': fps, 'loop': loop, 'joints': names, 'hipRef': round(hipRef, 4), 'floorSpeed': round(floorSpeed, 3),
        'hip': [round(float(v), 4) for v in hip], 'yaw': [round(float(v), 4) for v in yaw], 'pos': np.round(P, 4).tolist(),
        'source': os.path.basename(str(d['video'])) if 'video' in d.files else ''}
os.makedirs('src/mocap', exist_ok=True)
json.dump(clip, open(f'src/mocap/{name}.json', 'w'), separators=(',', ':'))
names_ = sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob('src/mocap/*.json'))
open('src/mocap/index.ts', 'w').write("// generated by scripts/mocap/build-clip.py\nimport type { MocapClip } from '../rigPose';\n" + ''.join(f"import c_{n.replace('-', '_')} from './{n}.json';\n" for n in names_)
  + "export const CLIPS: Record<string, MocapClip> = { " + ', '.join(f"'{n}': c_{n.replace('-', '_')} as unknown as MocapClip" for n in names_) + " };\n")
print(f'wrote src/mocap/{name}.json: {len(P)} frames at {fps} fps ({len(P) / fps:.2f} s), hipRef {hipRef:.3f} m, floor speed {floorSpeed:.2f} m/s, loop={loop}')
