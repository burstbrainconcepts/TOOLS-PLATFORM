"""Imports a recorded clip from Ara 3D Gen (MIT code; the motion is from the CMU Graphics Lab Motion Capture Database: free to use,
including commercially, but the data may not be resold on its own) into our clip format.
The clips in src/core/anim/clips/mocap-data.ts hold, per frame and per bone, a world rotation (int16 xyzw) relative to the source rest pose,
plus the rest direction of each limb. We turn those into joint positions by forward kinematics with nominal bone lengths, so the same
direction retargeting (rigPose.ts mocapDeltas) drives Ada. Data is only parsed as JSON, none of Ara's code is run.
Usage: python import-ara.py <mocap-data.ts> <ara-clip-name> <our-name> [--travel-z M_PER_S_OVERRIDE]
Names in that file: walk model_walk walk_slouch run strafe_right strafe_left jump laugh_hard cry sit_down sit_idle punch_low turn_*"""
import json, sys, base64, os, glob, numpy as np
src, an, name = sys.argv[1:4]
s = open(src).read(); D = json.JSONDecoder().raw_decode(s[s.index('= {') + 2:])[0][an]
bones, nf = D['bones'], D['frames']; nb = len(bones); bi = {b: i for i, b in enumerate(bones)}
Q = np.frombuffer(base64.b64decode(D['rot']), '<i2').astype(float).reshape(nf, nb, 4) / 32767.0
Q /= np.linalg.norm(Q, axis=2, keepdims=True)
H = np.frombuffer(base64.b64decode(D['hips']), '<i2').astype(float).reshape(nf, 3) / 10000.0
def qrot(q, v):
    x, y, z, w = q; u = np.array([x, y, z]); return 2 * u.dot(v) * u + (w * w - u.dot(u)) * v + 2 * w * np.cross(u, v)
rest = {'Hips': (0, 1, 0), 'Spine': (0, 1, 0), 'Spine1': (0, 1, 0), 'Spine2': (0, 1, 0), 'Neck': (0, 1, 0), 'Head': (0, 1, 0),
        'LeftShoulder': (1, 0, 0), 'RightShoulder': (-1, 0, 0), 'LeftFoot': (0, 0, 1), 'RightFoot': (0, 0, 1)}
rest.update({k: tuple(v) for k, v in D['dir'].items()})
seg = lambda f, b: qrot(Q[f, bi[b]], np.array(rest[b], float))        # world direction of a bone's segment in frame f
L = 0.95                                                                 # nominal standing hip height in metres (our unit; the retargeting only uses ratios)
names = ['pelvis', 'left_hip', 'right_hip', 'spine1', 'left_knee', 'right_knee', 'spine2', 'left_ankle', 'right_ankle', 'spine3', 'left_foot', 'right_foot', 'neck', 'left_collar', 'right_collar', 'head', 'left_shoulder', 'right_shoulder', 'left_elbow', 'right_elbow', 'left_wrist', 'right_wrist', 'left_hand', 'right_hand']
ix = {n: i for i, n in enumerate(names)}
P = np.zeros((nf, len(names), 3))
for f in range(nf):
    p = P[f]; O = np.array([0, 0.0, 0])
    p[ix['pelvis']] = O
    p[ix['spine1']] = p[ix['pelvis']] + seg(f, 'Hips') * 0.10
    p[ix['spine2']] = p[ix['spine1']] + seg(f, 'Spine') * 0.12
    p[ix['spine3']] = p[ix['spine2']] + seg(f, 'Spine1') * 0.12
    p[ix['neck']] = p[ix['spine3']] + seg(f, 'Spine2') * 0.15
    p[ix['head']] = p[ix['neck']] + seg(f, 'Neck') * 0.15
    for sd, X in (('left', 1), ('right', -1)):
        S = 'Left' if X > 0 else 'Right'
        p[ix[f'{sd}_hip']] = p[ix['pelvis']] + np.array([X * 0.09, 0, 0])
        p[ix[f'{sd}_knee']] = p[ix[f'{sd}_hip']] + seg(f, S + 'UpLeg') * 0.42
        p[ix[f'{sd}_ankle']] = p[ix[f'{sd}_knee']] + seg(f, S + 'Leg') * 0.42
        p[ix[f'{sd}_foot']] = p[ix[f'{sd}_ankle']] + seg(f, S + 'Foot') * 0.15
        p[ix[f'{sd}_collar']] = p[ix['neck']] + np.array([X * 0.02, -0.03, 0])
        p[ix[f'{sd}_shoulder']] = p[ix[f'{sd}_collar']] + seg(f, S + 'Shoulder') * 0.14
        p[ix[f'{sd}_elbow']] = p[ix[f'{sd}_shoulder']] + seg(f, S + 'Arm') * 0.28
        p[ix[f'{sd}_wrist']] = p[ix[f'{sd}_elbow']] + seg(f, S + 'ForeArm') * 0.26
        p[ix[f'{sd}_hand']] = p[ix[f'{sd}_wrist']] + seg(f, S + 'Hand') * 0.08
hip = H[:, 1] * L; P = P + 0 * P
tz = D.get('travel', [0, 0, 0])[2]; fps = (nf - 1) / D['duration']
clip = {'name': name, 'fps': round(fps, 3), 'loop': bool(D['loop']), 'joints': names, 'hipRef': round(float(np.percentile(hip, 75)), 4),
        'floorSpeed': round(abs(tz) * L / 1.8, 3), 'hip': [round(float(v), 4) for v in hip], 'yaw': [0.0] * nf,
        'pos': np.round(P, 4).tolist(), 'source': f'Ara 3D Gen / CMU mocap: {an}'}
os.makedirs('src/mocap', exist_ok=True); json.dump(clip, open(f'src/mocap/{name}.json', 'w'), separators=(',', ':'))
nm = sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob('src/mocap/*.json'))
open('src/mocap/index.ts', 'w').write("// generated by scripts/mocap/build-clip.py and import-ara.py\nimport type { MocapClip } from '../rigPose';\n" + ''.join(f"import c_{n.replace('-', '_')} from './{n}.json';\n" for n in nm)
  + "export const CLIPS: Record<string, MocapClip> = { " + ', '.join(f"'{n}': c_{n.replace('-', '_')} as unknown as MocapClip" for n in nm) + " };\n")
print(f'wrote src/mocap/{name}.json: {nf} frames at {fps:.1f} fps, loop={clip["loop"]}, hipRef {clip["hipRef"]}, floor {clip["floorSpeed"]} m/s')
