"""Procedural stylised human for the 3D mode. Run headless:
    blender -b -P models/build_human.py -- public/models/human.glb [preview.png]
Body: stick-figure skeleton -> Skin modifier -> Subdivision (smooth organic limbs with hands) -> material regions
(skin / shirt / pants), skinned to a real armature. Head: sculpted sphere with ears, nose, brow ridge, eye sockets; separate
parts (eyes, eyelids, brows, mouth, hair styles, glasses, shoes) so the renderer can animate and recolour them.
Character facing is -Y in Blender (= +Z in glTF). Bones are named by side: _p = +X side, _n = -X side. Units: metres.
Everything is generated by this script: no downloaded assets, no licences."""
import bpy, bmesh, math, sys, os
from mathutils import Vector

OUT = sys.argv[sys.argv.index('--') + 1] if '--' in sys.argv else 'human.glb'
PREVIEW = sys.argv[sys.argv.index('--') + 2] if '--' in sys.argv and len(sys.argv) > sys.argv.index('--') + 2 else None
bpy.ops.wm.read_factory_settings(use_empty=True)
scene = bpy.context.scene

def lin(h):
    h = h.lstrip('#'); c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    return [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c] + [1]

def mat(name, color, rough=0.6):
    m = bpy.data.materials.new(name); m.use_nodes = True
    b = m.node_tree.nodes['Principled BSDF']; b.inputs['Base Color'].default_value = lin(color); b.inputs['Roughness'].default_value = rough
    return m
M = {'skin': mat('skin', '#8D5524', 0.55), 'shirt': mat('shirt', '#2B6CFF', 0.7), 'pants': mat('pants', '#2A2F45', 0.75), 'shoe': mat('shoe', '#FFFFFF', 0.45),
     'hair': mat('hair', '#14100D', 0.85), 'eye_white': mat('eye_white', '#F4F4F2', 0.25), 'eye_dark': mat('eye_dark', '#1B1B1F', 0.2), 'mouth': mat('mouth', '#4A1620', 0.5),
     'trim': mat('trim', '#FFFFFF', 0.6)}
SLOT = ['skin', 'shirt', 'pants', 'shoe', 'hair', 'eye_white', 'eye_dark', 'mouth', 'trim']

def activate(o):
    bpy.ops.object.select_all(action='DESELECT'); o.select_set(True); bpy.context.view_layer.objects.active = o

def smooth(o):
    for p in o.data.polygons: p.use_smooth = True

def obj_from_bmesh(name, bm, loc=(0, 0, 0)):
    me = bpy.data.meshes.new(name); bm.to_mesh(me); bm.free()
    o = bpy.data.objects.new(name, me); scene.collection.objects.link(o); o.location = loc
    return o

def sphere(name, loc, scale, matname, seg=24, rings=14, radius=1.0, part=None):
    bm = bmesh.new(); bmesh.ops.create_uvsphere(bm, u_segments=seg, v_segments=rings, radius=radius)
    if part == 'upper':   # keep the upper half only (eyelids)
        bmesh.ops.delete(bm, geom=[v for v in bm.verts if v.co.z < -1e-4], context='VERTS')
    o = obj_from_bmesh(name, bm, loc); o.scale = scale; o.data.materials.append(M[matname]); smooth(o); return o

# ---------------------------------------------------------------- body (skin modifier on a stick figure)
V = {}
edges = []
def v(name, p, r): V[name] = (Vector(p), r)
def e(a, b): edges.append((a, b))

v('pelvis', (0, 0, 0.95), (0.185, 0.115)); v('spine', (0, 0, 1.10), (0.165, 0.105)); v('chest', (0, 0, 1.30), (0.205, 0.120))
v('chestU', (0, 0, 1.40), (0.20, 0.112)); v('neckB', (0, 0, 1.48), (0.085, 0.080)); v('neckT', (0, 0, 1.585), (0.062, 0.062))
for a, b in (('pelvis', 'spine'), ('spine', 'chest'), ('chest', 'chestU'), ('chestU', 'neckB'), ('neckB', 'neckT')): e(a, b)
for s, x in (('p', 1), ('n', -1)):
    v(f'sh_{s}', (0.225 * x, 0, 1.415), (0.072, 0.072)); v(f'el_{s}', (0.262 * x, 0, 1.14), (0.052, 0.052)); v(f'wr_{s}', (0.27 * x, 0, 0.90), (0.034, 0.030))
    v(f'palm_{s}', (0.283 * x, 0, 0.80), (0.042, 0.018)); v(f'palmE_{s}', (0.288 * x, 0, 0.745), (0.040, 0.016))
    v(f'th_{s}', (0.250 * x, -0.045, 0.795), (0.016, 0.016))
    for i, (dx, dy) in enumerate(((0.012, -0.022), (0.0, -0.008), (-0.012, 0.006), (-0.022, 0.02))):
        v(f'f{i}_{s}', ((0.296 + dx * 0.6) * x, dy * 0.5, 0.675 - i * 0.004), (0.0115, 0.0115)); e(f'palmE_{s}', f'f{i}_{s}')
    e('chestU', f'sh_{s}'); e(f'sh_{s}', f'el_{s}'); e(f'el_{s}', f'wr_{s}'); e(f'wr_{s}', f'palm_{s}'); e(f'palm_{s}', f'palmE_{s}'); e(f'palm_{s}', f'th_{s}')
    v(f'hp_{s}', (0.100 * x, 0, 0.92), (0.105, 0.105)); v(f'kn_{s}', (0.105 * x, 0, 0.50), (0.078, 0.076)); v(f'an_{s}', (0.100 * x, 0, 0.115), (0.050, 0.048)); v(f'toe_{s}', (0.100 * x, -0.11, 0.055), (0.046, 0.038))
    e('pelvis', f'hp_{s}'); e(f'hp_{s}', f'kn_{s}'); e(f'kn_{s}', f'an_{s}'); e(f'an_{s}', f'toe_{s}')

bm = bmesh.new(); idx = {}
for n, (p, r) in V.items(): idx[n] = bm.verts.new(p)
bm.verts.ensure_lookup_table()
for a, b in edges: bm.edges.new((idx[a], idx[b]))
body = obj_from_bmesh('body', bm)
activate(body)
bpy.ops.object.modifier_add(type='SKIN'); sk = body.modifiers['Skin']; sk.branch_smoothing = 0.6; sk.use_smooth_shade = True
for n, (p, r) in V.items():
    i = list(V).index(n); body.data.skin_vertices[0].data[i].radius = r
body.data.skin_vertices[0].data[list(V).index('pelvis')].use_root = True
bpy.ops.object.modifier_apply(modifier='Skin')
for m in SLOT: body.data.materials.append(M[m])
# material regions by face position: shirt (torso + short sleeves), pants (hips + legs), skin (neck, forearms, hands, ankles)
for p in body.data.polygons:
    c = p.center; z, ax = c.z, abs(c.x)
    if z >= 1.50: p.material_index = 0
    elif z >= 0.97 and (ax < 0.235 or z >= 1.14) and not (z < 1.14 and ax >= 0.235): p.material_index = 1
    elif 0.11 < z < 0.97 and ax < 0.22: p.material_index = 2
    else: p.material_index = 0

bpy.ops.object.modifier_add(type='SUBSURF'); body.modifiers['Subdivision'].levels = 2; body.modifiers['Subdivision'].render_levels = 2
bpy.ops.object.modifier_apply(modifier='Subdivision')
smooth(body)
# ---------------------------------------------------------------- head (sculpted sphere)
HC = Vector((0, 0, 1.70))
bm = bmesh.new(); bmesh.ops.create_uvsphere(bm, u_segments=40, v_segments=28, radius=1.0)
def bump(p, c, s, amp):   # gaussian displacement weight
    return amp * math.exp(-((p - c).length_squared) / (2 * s * s))
for vt in bm.verts:
    x, y, z = vt.co.x, vt.co.y, vt.co.z                       # unit sphere coords, front is -Y
    sx, sy, sz = 0.112, 0.112, 0.122                           # head proportions (wider, rounder)
    if z < 0: x *= 1 - 0.16 * (-z) ** 1.3; y *= 1 - 0.08 * (-z)  # jaw taper
    p = Vector((x * sx, y * sy, z * sz))
    front = Vector((0, -sy, 0))
    p.y += bump(p, Vector((0, -0.110, -0.014)), 0.021, -0.024) * (1 if p.y < 0 else 0)          # nose pushes forward (-Y)
    p.y += bump(p, Vector((0, -0.105, 0.040)), 0.030, -0.006) * (1 if p.y < 0 else 0)            # brow ridge
    for sgn in (-1, 1):
        p.y += bump(p, Vector((sgn * 0.040, -0.098, 0.016)), 0.016, 0.0065) * (1 if p.y < 0 else 0)   # eye sockets (inward)
        p.y += bump(p, Vector((sgn * 0.060, -0.085, -0.030)), 0.028, -0.007) * (1 if p.y < 0 else 0)  # cheeks
    p.y += bump(p, Vector((0, -0.095, -0.080)), 0.026, -0.006) * (1 if p.y < 0 else 0)              # chin
    vt.co = p
head = obj_from_bmesh('head_mesh', bm, HC); head.data.materials.append(M['skin']); smooth(head)
for sgn in (-1, 1):
    ear = sphere(f'ear_{"p" if sgn > 0 else "n"}', HC + Vector((sgn * 0.110, 0.004, -0.004)), (0.011, 0.020, 0.030), 'skin')
# eyes: white ball, dark iris/pupil, upper lid (pivot at eye centre so rotating it blinks)
for sgn, s in ((-1, 'n'), (1, 'p')):
    ec = HC + Vector((sgn * 0.040, -0.088, 0.016))
    sphere(f'eye_{s}', ec, (0.0195, 0.0195, 0.0195), 'eye_white')
    sphere(f'pupil_{s}', ec + Vector((0, -0.0135, 0)), (0.0105, 0.0075, 0.0105), 'eye_dark', seg=16, rings=10)
    lid = sphere(f'lid_{s}', ec, (0.0215, 0.0215, 0.0215), 'skin', part='upper')
    lid.rotation_euler[0] = math.radians(-70)               # rest = open (hood tucked up); the renderer rotates it down to blink
    br = sphere(f'brow_{s}', HC + Vector((sgn * 0.041, -0.1035, 0.052)), (0.022, 0.0065, 0.0065), 'hair', seg=12, rings=8)
# mouth parts (visibility switched by the renderer): open (scaled with the voice), smile arc, flat line
mo = sphere('mouth_open', HC + Vector((0, -0.100, -0.052)), (0.022, 0.006, 0.007), 'mouth', seg=16, rings=10)
bm = bmesh.new(); bmesh.ops.create_circle(bm, cap_ends=False, radius=1, segments=24)
bpy.ops.mesh.primitive_torus_add(major_radius=0.022, minor_radius=0.0042, major_segments=24, minor_segments=8, location=HC + Vector((0, -0.100, -0.046)), rotation=(math.radians(90), 0, 0))
sm = bpy.context.active_object; sm.name = 'mouth_smile'; sm.scale = (1, 1, 0.55); sm.data.materials.append(M['eye_dark']); smooth(sm)
# keep only the lower half of the torus (a smile): delete verts with z above centre
bm = bmesh.new(); bm.from_mesh(sm.data); bmesh.ops.delete(bm, geom=[vv for vv in bm.verts if vv.co.z > 0.0005], context='VERTS'); bm.to_mesh(sm.data); bm.free()
fl = sphere('mouth_flat', HC + Vector((0, -0.100, -0.052)), (0.0155, 0.0038, 0.0042), 'eye_dark', seg=12, rings=8)
# nose already sculpted. glasses (optional, shown by the renderer)
gl = []
for sgn in (-1, 1):
    bpy.ops.mesh.primitive_torus_add(major_radius=0.030, minor_radius=0.0042, major_segments=28, minor_segments=8, location=HC + Vector((sgn * 0.040, -0.104, 0.016)), rotation=(math.radians(90), 0, 0))
    g = bpy.context.active_object; g.name = f'glass_{"p" if sgn > 0 else "n"}'; g.data.materials.append(M['eye_dark']); smooth(g); gl.append(g)
bpy.ops.mesh.primitive_cube_add(size=1, location=HC + Vector((0, -0.106, 0.018))); br_ = bpy.context.active_object; br_.name = 'glass_bridge'; br_.scale = (0.018, 0.004, 0.004); br_.data.materials.append(M['eye_dark'])
# hair styles (the renderer shows one): short cap, puff, helmet
def hair_cap(name, lift, tilt, size):
    bm = bmesh.new(); bmesh.ops.create_uvsphere(bm, u_segments=36, v_segments=20, radius=1.0)
    bmesh.ops.delete(bm, geom=[vv for vv in bm.verts if vv.co.z < -0.15 or (vv.co.z < 0.35 and vv.co.y < -0.35)], context='VERTS')
    o = obj_from_bmesh(name, bm, HC + Vector((0, 0.004, lift))); o.scale = size; o.rotation_euler[0] = math.radians(tilt); o.data.materials.append(M['hair']); smooth(o); return o
hair_cap('hair_short', 0.004, -8, (0.108, 0.118, 0.132))
hair_cap('hair_helmet', 0.0, -2, (0.112, 0.122, 0.138))
puff = []
for i, (x, y, z, r) in enumerate([(-0.065, 0.0, 0.085, 0.058), (0.065, 0.0, 0.085, 0.058), (0, -0.005, 0.115, 0.072), (-0.04, -0.045, 0.098, 0.052), (0.04, -0.045, 0.098, 0.052), (0, 0.07, 0.07, 0.07), (-0.07, 0.05, 0.03, 0.05), (0.07, 0.05, 0.03, 0.05)]):
    puff.append(sphere(f'puff{i}', HC + Vector((x, y, z)), (r, r, r), 'hair', seg=20, rings=12))
activate(puff[0])
for o in puff: o.select_set(True)
bpy.ops.object.join(); bpy.context.active_object.name = 'hair_puff'

# shoes
for s, x in (('p', 1), ('n', -1)):
    sh = sphere(f'shoe_{s}', Vector((0.100 * x, -0.055, 0.055)), (0.058, 0.135, 0.052), 'shoe', seg=28, rings=16)
    sole = sphere(f'sole_{s}', Vector((0.100 * x, -0.05, 0.016)), (0.060, 0.140, 0.020), 'trim', seg=28, rings=10)

# ---------------------------------------------------------------- armature
bpy.ops.object.armature_add(enter_editmode=True, location=(0, 0, 0)); arm = bpy.context.active_object; arm.name = 'rig'; arm.data.name = 'rig'
eb = arm.data.edit_bones; eb.remove(eb[0])
def bone(name, h, t, parent=None):
    b = eb.new(name); b.head = Vector(h); b.tail = Vector(t)
    if parent: b.parent = eb[parent]; b.use_connect = False
    return b
bone('hips', (0, 0, 0.93), (0, 0, 1.08)); bone('spine', (0, 0, 1.08), (0, 0, 1.30), 'hips'); bone('chest', (0, 0, 1.30), (0, 0, 1.47), 'spine')
bone('neck', (0, 0, 1.47), (0, 0, 1.60), 'chest'); bone('head', (0, 0, 1.60), (0, 0, 1.82), 'neck')
for s, x in (('p', 1), ('n', -1)):
    bone(f'upperarm_{s}', (0.225 * x, 0, 1.415), (0.262 * x, 0, 1.14), 'chest'); bone(f'forearm_{s}', (0.262 * x, 0, 1.14), (0.27 * x, 0, 0.90), f'upperarm_{s}')
    bone(f'hand_{s}', (0.27 * x, 0, 0.90), (0.285 * x, 0, 0.68), f'forearm_{s}')
    bone(f'thigh_{s}', (0.095 * x, 0, 0.93), (0.100 * x, 0, 0.50), 'hips'); bone(f'shin_{s}', (0.100 * x, 0, 0.50), (0.100 * x, 0, 0.115), f'thigh_{s}')
    bone(f'foot_{s}', (0.100 * x, 0, 0.115), (0.100 * x, -0.14, 0.045), f'shin_{s}')
bpy.ops.object.mode_set(mode='OBJECT')
# automatic weights for the body (heat map): needs a clean mesh, which skin + subdivision gives
activate(body); arm.select_set(True); bpy.context.view_layer.objects.active = arm
bpy.ops.object.parent_set(type='ARMATURE_AUTO')
vg = {g.name for g in body.vertex_groups}
print('weighted groups:', len(vg), 'of 17 bones')

# ---------------------------------------------------------------- export
for o in list(scene.objects): o.select_set(o.type in ('MESH', 'ARMATURE'))
bpy.context.view_layer.objects.active = arm
os.makedirs(os.path.dirname(os.path.abspath(OUT)), exist_ok=True)
bpy.ops.export_scene.gltf(filepath=OUT, export_format='GLB', use_selection=True, export_apply=True, export_yup=True, export_skins=True, export_animations=False, export_morph=False)
print('exported', OUT, os.path.getsize(OUT) // 1024, 'KB')
if PREVIEW:   # quick Workbench preview so the model can be checked without three.js
    cam = bpy.data.objects.new('cam', bpy.data.cameras.new('cam')); scene.collection.objects.link(cam); scene.camera = cam
    cam.location = (0, -4.5, 1.0); cam.rotation_euler = (math.radians(90), 0, 0); cam.data.lens = 70
    scene.render.engine = 'BLENDER_WORKBENCH'; scene.display.shading.light = 'STUDIO'; scene.display.shading.color_type = 'MATERIAL'
    scene.render.resolution_x, scene.render.resolution_y = 600, 900; scene.render.filepath = PREVIEW
    scene.world = bpy.data.worlds.new('w'); scene.world.color = (0.55, 0.6, 0.7)
    bpy.ops.render.render(write_still=True)
